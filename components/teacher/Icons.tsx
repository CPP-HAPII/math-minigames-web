export type IconName = keyof typeof PATHS;

export default function Icon({
  name,
  size = 18,
  color = 'currentColor',
  strokeWidth = 1.75,
}: {
  name: IconName;
  size?: number;
  color?: string;
  strokeWidth?: number;
}) {
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke={color}
      strokeWidth={strokeWidth}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      focusable="false"
      style={{ flex: 'none' }}
    >
      {PATHS[name]}
    </svg>
  );
}

/** Icon for a logged assist-interaction event; a neutral mark for types we don't know yet. */
export function interactionIcon(interaction: string): IconName {
  if (interaction === 'translation_displayed') return 'eye';
  if (interaction === 'hover_translation') return 'pointer';
  if (interaction === 'translation_heard') return 'volume';
  return 'sparkle';
}
